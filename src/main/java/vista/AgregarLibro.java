    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        
        String titulo = jTextField1.getText();
        double precio = Double.parseDouble(jTextField2.getText());
        int cantidadEnInventario = Integer.parseInt(jTextField3.getText());
        String autor = jTextField4.getText();
        Libro.autores.add(autor);
        String isbn = jTextField5.getText();
        
        try {
            TiendaDeLibros.agregarLibro(titulo, precio, cantidadEnInventario, autor, isbn);
        } catch (IOException ex) {
            System.getLogger(AgregarLibro.class.getName()).log(System.Logger.Level.ERROR, (String) null, ex);
        }
        
        this.setVisible(false);
        PantallaPrincipal pp = new PantallaPrincipal(this.controladorAHeredar);
        pp.setVisible(true);
        
    }//GEN-LAST:event_jButton1ActionPerformed

